// ROCK PAPER SCISSORS' MANIFEST VERSION 13, SIGNED BY ITS DEVELOPER: version 12 in every term but its client - client/index-v13.html (version 12's,
// written by tools/build-client-v13.mjs: it asks the seats for a round's players only for the round on screen and the one before it, a round at
// most every 4 s with a back-off on 404, and reads its own round's result at most every 3 s, not again once settled). The core is still version
// 4's (plugin/decide-v4.js): the rules and the scores do not change.
// Parent: version 12 (plugin/rock-paper-scissors-v12.js).
//
//   node tools/sign-manifest-v13.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/rock-paper-scissors-v13.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V12, GAME_ID_V12 } from '../plugin/rock-paper-scissors-v12.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v13.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V12.gameDevPubkey)) throw new Error(`that key is not Rock Paper Scissors' developer key ${toHex(MANIFEST_V12.gameDevPubkey).slice(0, 16)}`);
const hash = (u) => new Uint8Array(createHash('sha256').update(readFileSync(u)).digest());
const CORE = hash(new URL('../plugin/decide-v4.js', import.meta.url));
const CLIENT = hash(new URL('../client/index-v13.html', import.meta.url));
const { signature, ...v9body } = MANIFEST_V12;
void signature;
if (MANIFEST_V12.cores.length !== 1) throw new Error('version 12 names one core');
if (toHex(MANIFEST_V12.cores[0].hash) !== toHex(CORE)) throw new Error('version 12 keeps version 4\'s core, as versions 5 to 12 did');
const body = { ...v9body, version: MANIFEST_V12.version + 1, parentManifestId: GAME_ID_V12, clients: [CLIENT] };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V12) ? MANIFEST_V12 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/rock-paper-scissors-v13.js', import.meta.url), `// GENERATED by tools/sign-manifest-v13.mjs with the developer's signer - do not edit by hand. PUBLIC BYTES ONLY.
// rock-paper-scissors' GameManifest version 13: version 12 (${toHex(GAME_ID_V12)}) in every term but its client
// ${toHex(CLIENT)} (client/index-v13.html, asks the seats sparingly); its core is version 4's ${toHex(CORE)} (plugin/decide-v4.js); requires protocol version
// ${body.requiredProtocolVersion}. Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V4, RPS_DECIDE_V4_CORE, RPS_ROUND_FIELDS_V4 } from './rock-paper-scissors-v4.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V13_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V13 = decodeManifest(fromHex(MANIFEST_V13_HEX));
export const GAME_ID_V13 = gameIdOf(MANIFEST_V13);
export const RPS_CLIENT_V13_FILE = new URL('../client/index-v13.html', import.meta.url);
/** What a launcher loads from this module (ARENA_APPS): the registration, version 4's core and its client version 13's. */
export const GAME = Object.freeze({ ...V4, manifest: MANIFEST_V13, gameId: GAME_ID_V13, cores: new Map([[RPS_DECIDE_V4_CORE.hash, RPS_DECIDE_V4_CORE]]), clientUrls: [RPS_CLIENT_V13_FILE.href] });
/** A version-13 round's fields: its game, version 4's core and config and timing. */
export const RPS_ROUND_FIELDS_V13 = Object.freeze({ ...RPS_ROUND_FIELDS_V4, gameId: GAME_ID_V13 });
`);
console.log(`rock-paper-scissors v${body.version}: parent ${toHex(GAME_ID_V12).slice(0, 16)}, core ${toHex(CORE).slice(0, 12)}, client ${toHex(CLIENT).slice(0, 12)}, game_id ${id}`);
