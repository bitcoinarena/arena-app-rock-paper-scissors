// ROCK PAPER SCISSORS' MANIFEST VERSION 10, SIGNED BY ITS DEVELOPER: version 9 in every term but its client - client/index-v10.html (version 9's
// with the hands drawn as SVG, nothing cut off above the title, and a paid round's stake and fees said; written by tools/build-client-v10.mjs). The core is
// still version 4's (plugin/decide-v4.js): the rules and the scores do not change. Parent: version 9 (plugin/rock-paper-scissors-v9.js).
//
//   node tools/sign-manifest-v10.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/rock-paper-scissors-v10.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V9, GAME_ID_V9 } from '../plugin/rock-paper-scissors-v9.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v10.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V9.gameDevPubkey)) throw new Error(`that key is not Rock Paper Scissors' developer key ${toHex(MANIFEST_V9.gameDevPubkey).slice(0, 16)}`);
const hash = (u) => new Uint8Array(createHash('sha256').update(readFileSync(u)).digest());
const CORE = hash(new URL('../plugin/decide-v4.js', import.meta.url));
const CLIENT = hash(new URL('../client/index-v10.html', import.meta.url));
const { signature, ...v9body } = MANIFEST_V9;
void signature;
if (MANIFEST_V9.cores.length !== 1) throw new Error('version 9 names one core');
if (toHex(MANIFEST_V9.cores[0].hash) !== toHex(CORE)) throw new Error('version 10 keeps version 4\'s core, as versions 5 to 9 did');
const body = { ...v9body, version: MANIFEST_V9.version + 1, parentManifestId: GAME_ID_V9, clients: [CLIENT] };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V9) ? MANIFEST_V9 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/rock-paper-scissors-v10.js', import.meta.url), `// GENERATED by tools/sign-manifest-v10.mjs with the developer's signer - do not edit by hand. PUBLIC BYTES ONLY.
// rock-paper-scissors' GameManifest version 10: version 9 (${toHex(GAME_ID_V9)}) in every term but its client
// ${toHex(CLIENT)} (client/index-v10.html, the hands drawn, the stake said); its core is version 4's ${toHex(CORE)} (plugin/decide-v4.js); requires protocol version
// ${body.requiredProtocolVersion}. Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V4, RPS_DECIDE_V4_CORE, RPS_ROUND_FIELDS_V4 } from './rock-paper-scissors-v4.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V10_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V10 = decodeManifest(fromHex(MANIFEST_V10_HEX));
export const GAME_ID_V10 = gameIdOf(MANIFEST_V10);
export const RPS_CLIENT_V10_FILE = new URL('../client/index-v10.html', import.meta.url);
/** What a launcher loads from this module (ARENA_APPS): the registration, version 4's core and its client version 10's. */
export const GAME = Object.freeze({ ...V4, manifest: MANIFEST_V10, gameId: GAME_ID_V10, cores: new Map([[RPS_DECIDE_V4_CORE.hash, RPS_DECIDE_V4_CORE]]), clientUrls: [RPS_CLIENT_V10_FILE.href] });
/** A version-10 round's fields: its game, version 4's core and config and timing. */
export const RPS_ROUND_FIELDS_V10 = Object.freeze({ ...RPS_ROUND_FIELDS_V4, gameId: GAME_ID_V10 });
`);
console.log(`rock-paper-scissors v${body.version}: parent ${toHex(GAME_ID_V9).slice(0, 16)}, core ${toHex(CORE).slice(0, 12)}, client ${toHex(CLIENT).slice(0, 12)}, game_id ${id}`);
